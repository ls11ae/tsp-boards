// Markdown review report for a country data build (committed as docs/data/<cc>-report.md).

import { CityFlag, type CountryFile, type City } from '../../src/core/data';
import type { NameSource } from './geonames';

export interface ReportInput {
  readonly file: CountryFile;
  readonly cities: readonly City[];
  readonly nameSources: ReadonlyMap<number, NameSource>;
  readonly geonamesRows: number;
  readonly municipalities: number;
  readonly outsideState: readonly City[];
  readonly overridesApplied: number;
  readonly fileBytes: number;
}

const fmt = (n: number) => n.toLocaleString('en-US');

function flagNames(flags: number): string {
  const names = Object.entries(CityFlag)
    .filter(([, bit]) => flags & bit)
    .map(([name]) => name);
  return names.join(', ');
}

function cityTable(cities: readonly City[], limit: number): string[] {
  const lines = [
    '| GeoNames id | name | label | English | population | state | flags |',
    '|---|---|---|---|---|---|---|',
  ];
  for (const c of cities.slice(0, limit)) {
    lines.push(
      `| ${c.id} | ${c.name} | ${c.label === c.name ? '' : c.label} | ${c.nameEn === c.name ? '' : c.nameEn} | ${fmt(c.pop)} | ${c.state} | ${flagNames(c.flags)} |`,
    );
  }
  if (cities.length > limit) lines.push(`| … ${cities.length - limit} more | | | | | | |`);
  return lines;
}

export function renderReport(input: ReportInput): string {
  const { file, cities } = input;
  const lines: string[] = [];
  lines.push(`# Data report: ${file.name.en} (${file.country})`, '');
  lines.push(
    `Generated by \`npm run data:build -- ${file.country.toLowerCase()}\`. Data version ${file.dataVersion}, ` +
      `content hash \`${file.contentHash.slice(0, 19)}…\`, file size ${fmt(Math.round(input.fileBytes / 1024))} KB.`,
    '',
  );

  lines.push('## Sources', '');
  for (const s of file.sources) {
    for (const f of s.files) {
      lines.push(
        `- ${s.name} (${s.license}): ${f.url}, last modified ${f.lastModified ?? 'unknown'}, sha256 \`${f.sha256.slice(0, 16)}…\``,
      );
    }
  }
  lines.push('');

  lines.push('## Counts', '');
  lines.push(
    `- GeoNames rows kept for processing (populated places and ADM4): ${fmt(input.geonamesRows)}`,
  );
  lines.push(`- Municipalities (groups by admin1/admin4): ${fmt(input.municipalities)}`);
  lines.push(`- Cities with population ≥ ${fmt(file.minPopulation)}: **${fmt(cities.length)}**`);
  lines.push(`- Manual overrides applied: ${input.overridesApplied}`);
  lines.push('');
  const bands = [1_000, 5_000, 10_000, 20_000, 50_000, 100_000, 500_000];
  lines.push('| population ≥ | cities |', '|---|---|');
  for (const b of bands)
    lines.push(`| ${fmt(b)} | ${fmt(cities.filter((c) => c.pop >= b).length)} |`);
  lines.push('');

  lines.push('### Cities per state', '');
  lines.push('| state | name | cities | ≥ 10,000 | largest |', '|---|---|---|---|---|');
  for (const s of file.states) {
    const inState = cities.filter((c) => c.state === s.id);
    lines.push(
      `| ${s.id} | ${s.name} | ${fmt(inState.length)} | ${fmt(inState.filter((c) => c.pop >= 10_000).length)} | ${inState[0]?.name ?? ''} |`,
    );
  }
  lines.push('');

  lines.push('### Name sources', '');
  const sources = new Map<NameSource, number>();
  for (const s of input.nameSources.values()) sources.set(s, (sources.get(s) ?? 0) + 1);
  for (const [s, n] of [...sources].sort((a, b) => b[1] - a[1]))
    lines.push(`- \`${s}\`: ${fmt(n)}`);
  lines.push('');

  lines.push('## Largest 40 cities', '', ...cityTable(cities, 40), '');

  const flagged = (bit: number) => cities.filter((c) => c.flags & bit);
  lines.push(
    '## Review lists',
    '',
    `### Near a much larger city (possible districts): ${flagged(CityFlag.NearLarger).length}`,
    '',
    ...cityTable(flagged(CityFlag.NearLarger), 60),
    '',
    `### Ambiguous short labels (full name used as label): ${flagged(CityFlag.AmbiguousLabel).length}`,
    '',
    ...cityTable(
      flagged(CityFlag.AmbiguousLabel).filter((c) => c.pop >= 5_000),
      60,
    ),
    '',
    `### Duplicate names (≥ 5,000 shown): ${flagged(CityFlag.DuplicateName).length}`,
    '',
    ...cityTable(
      flagged(CityFlag.DuplicateName).filter((c) => c.pop >= 5_000),
      60,
    ),
    '',
    `### Municipality point used (no populated place): ${flagged(CityFlag.MunicipalityPoint).length}`,
    '',
    ...cityTable(flagged(CityFlag.MunicipalityPoint), 30),
    '',
  );
  const long = cities.filter((c) => c.label.length > 22);
  lines.push(
    `### Long labels (> 22 characters, ≥ 5,000 shown): ${long.length}`,
    '',
    ...cityTable(
      long.filter((c) => c.pop >= 5_000),
      60,
    ),
    '',
  );
  lines.push(
    `### Outside their state's simplified polygon: ${input.outsideState.length}`,
    '',
    'Usually coastal or border towns just outside the simplified outline.',
    '',
    ...cityTable(input.outsideState, 40),
    '',
  );
  return lines.join('\n');
}
