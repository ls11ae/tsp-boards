// Extracts glyph outlines and metrics of the board font into src/core/board/font-data.ts, so the
// core can measure text and convert it to paths without a font parser at runtime (laser
// software needs text as outlines). Usage: npm run font:build

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import opentype, { type PathCommand } from 'opentype.js';

const ROOT = path.resolve(import.meta.dirname, '../..');
const SOURCE = path.join(
  ROOT,
  'node_modules/@fontsource/fira-sans-condensed/files/fira-sans-condensed-latin-500-normal.woff',
);
const PACKAGE = path.join(ROOT, 'node_modules/@fontsource/fira-sans-condensed/package.json');
const OUTPUT = path.join(ROOT, 'src/core/board/font-data.ts');

/** Printable ASCII, Latin-1 and a few typographic characters for titles and instructions. */
function characterSet(): string[] {
  const chars: string[] = [];
  for (let c = 0x20; c <= 0x7e; c++) chars.push(String.fromCharCode(c));
  for (let c = 0xa0; c <= 0xff; c++) chars.push(String.fromCharCode(c));
  chars.push(...'–—‘’‚“”„…•€−←→↑↓');
  return chars;
}

function encodePath(commands: readonly PathCommand[]): string {
  const r = (v: number | undefined) => Math.round(v ?? 0);
  let at = '';
  return commands
    .map((c) => {
      const to = `${r(c.x)} ${r(c.y)}`;
      const previous = at;
      at = to;
      switch (c.type) {
        case 'M':
          return `M${to}`;
        case 'L':
          // Zero-length lines (the font closes curves explicitly) carry no information.
          return to === previous ? '' : `L${to}`;
        case 'Q':
          return `Q${r(c.x1)} ${r(c.y1)} ${r(c.x)} ${r(c.y)}`;
        case 'C':
          return `C${r(c.x1)} ${r(c.y1)} ${r(c.x2)} ${r(c.y2)} ${r(c.x)} ${r(c.y)}`;
        case 'Z':
          return 'Z';
      }
    })
    .join('');
}

/** Bounding box of all on- and off-curve points (a superset of the ink). */
function bounds(commands: readonly PathCommand[]): [number, number, number, number] {
  let [x0, y0, x1, y1] = [Infinity, Infinity, -Infinity, -Infinity];
  for (const c of commands) {
    for (const [x, y] of [
      [c.x, c.y],
      [c.x1, c.y1],
      [c.x2, c.y2],
    ] as const) {
      if (x === undefined || y === undefined) continue;
      x0 = Math.min(x0, x);
      y0 = Math.min(y0, y);
      x1 = Math.max(x1, x);
      y1 = Math.max(y1, y);
    }
  }
  if (x0 === Infinity) return [0, 0, 0, 0];
  return [Math.round(x0), Math.round(y0), Math.round(x1), Math.round(y1)];
}

async function main(): Promise<void> {
  const buffer = await readFile(SOURCE);
  const font = opentype.parse(
    buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength),
  );
  const { version } = JSON.parse(await readFile(PACKAGE, 'utf8')) as { version: string };
  const names = font.names.windows ?? {};
  const name = names.fullName?.en ?? 'Fira Sans Condensed Medium';
  const fontVersion = names.version?.en ?? '';
  const copyright = names.copyright?.en ?? '';

  const glyphs: Record<string, [number, number, number, number, number, string]> = {};
  const missing: string[] = [];
  for (const ch of characterSet()) {
    const glyph = font.charToGlyph(ch);
    if (glyph.index === 0) {
      missing.push(ch);
      continue;
    }
    const commands = glyph.path.commands;
    glyphs[ch] = [Math.round(glyph.advanceWidth), ...bounds(commands), encodePath(commands)];
  }

  const data = {
    name,
    unitsPerEm: font.unitsPerEm,
    ascender: font.ascender,
    descender: font.descender,
    capHeight: font.tables.os2.sCapHeight,
    xHeight: font.tables.os2.sxHeight,
    glyphs,
  };
  const source = `// Generated by scripts/build-font/build.ts — do not edit.
// ${name} (${fontVersion}), from @fontsource/fira-sans-condensed ${version}, latin subset.
// ${copyright}
// Licensed under the SIL Open Font License 1.1 (https://openfontlicense.org).
// Glyphs: [advance, xMin, yMin, xMax, yMax, outline]; font units, y up; outline commands
// M/L/Q/C/Z with absolute integer coordinates. No kerning (the subset carries none).

export interface FontData {
  readonly name: string;
  readonly unitsPerEm: number;
  readonly ascender: number;
  readonly descender: number;
  readonly capHeight: number;
  readonly xHeight: number;
  readonly glyphs: Readonly<
    Record<string, readonly [number, number, number, number, number, string] | undefined>
  >;
}

export const FONT_DATA: FontData = ${JSON.stringify(data)};
`;
  await writeFile(OUTPUT, source);
  console.log(
    `${Object.keys(glyphs).length} glyphs, ${source.length} bytes -> ${path.relative(ROOT, OUTPUT)}`,
  );
  if (missing.length > 0) console.log(`not in the font: ${missing.join(' ')}`);
}

await main();
